// Bundles the bridge for the browser and writes it as a module the content Worker imports:
// `dist/bundle.ts` exports the script and a version derived from its bytes, which the Worker
// puts in the script URL so a new bridge is never served from an old cache entry.
import { mkdir } from "node:fs/promises";

const root = new URL("..", import.meta.url).pathname;
const result = await Bun.build({
  entrypoints: [`${root}src/entry.ts`],
  target: "browser",
  format: "iife",
  minify: true,
});
const [output] = result.outputs;
if (!result.success || !output) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const script = await output.text();
const digest = new Bun.CryptoHasher("sha256").update(script).digest("hex");
await mkdir(`${root}dist`, { recursive: true });
await Bun.write(
  `${root}dist/bundle.ts`,
  `// Generated by packages/bridge/scripts/build.ts. Do not edit.\nexport const BRIDGE_SCRIPT: string = ${JSON.stringify(script)};\nexport const BRIDGE_VERSION: string = "${digest.slice(0, 16)}";\n`,
);
console.log(`bridge bundle: ${script.length} bytes, version ${digest.slice(0, 16)}`);
